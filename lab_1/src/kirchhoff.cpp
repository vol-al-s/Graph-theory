#include "../header/general.h"
#include <iostream>
#include <vector>
#include <cmath>

// =============================================================================
//                          ТЕОРЕМА КИРХГОФА
//
// Источник: tg9.pdf, слайд 49.
//
// Матрица Кирхгофа B(G) для неориентированного графа G:
//   B[i][i] =  deg(i)             — степень вершины i
//   B[i][j] = -A[i][j]   (i ≠ j)  — минус матрица смежности
//
// Число остовных деревьев = алгебраическому дополнению ЛЮБОГО элемента B(G).
// Все алгебраические дополнения равны между собой (это и есть утверждение теоремы).
//
// На практике удобнее всего вычислять алгебраическое дополнение B[0][0]:
// это просто определитель матрицы B без 1-й строки и 1-го столбца, т.е.
// определитель (n-1)×(n-1) матрицы.
//
// Определитель целочисленной симметричной матрицы вычисляем методом Гаусса
// с использованием рациональной арифметики через double (для нашего размера
// графов точности хватает с большим запасом; для больших графов следовало бы
// взять алгоритм Барейсса в целых числах).
// =============================================================================

long long Graph::countSpanningTreesKirchhoff() const {
    // Краевой случай 1: один или ноль вершин.
    // В теореме Кирхгофа явно сказано "n >= 2", значит для n < 2 теорема
    // неприменима. Для n = 1 принято считать, что есть 1 "пустое" остовное
    // дерево; для n = 0 — 0.
    if (vertexCount == 0) return 0;
    if (vertexCount == 1) return 1;

    // Краевой случай 2: ровно 2 вершины — это ровно случай K2 из лекции.
    // Если между ними есть ребро — 1 остовное дерево, если нет — 0 (граф несвязен).
    if (vertexCount == 2) {
        return undirectedMatrix.at(0, 1) == 1 ? 1 : 0;
    }

    // Строим матрицу Кирхгофа n×n.
    int n = vertexCount;
    std::vector<std::vector<double>> B(n, std::vector<double>(n, 0.0));

    for (int i = 0; i < n; i++) {
        int deg = 0;
        for (int j = 0; j < n; j++) {
            if (i == j) continue;
            if (undirectedMatrix.at(i, j) == 1) {
                B[i][j] = -1.0;
                deg++;
            }
        }
        B[i][i] = (double)deg;
    }

    // Возьмём алгебраическое дополнение M[0][0] = det( B без 1-й строки и 1-го столбца ).
    int m = n - 1;
    std::vector<std::vector<double>> M(m, std::vector<double>(m, 0.0));
    for (int i = 0; i < m; i++)
        for (int j = 0; j < m; j++)
            M[i][j] = B[i + 1][j + 1];

    // Метод Гаусса для определителя. Знак учитываем по числу перестановок строк.
    double det = 1.0;
    for (int col = 0; col < m; col++) {
        // 1) выбор ведущего элемента — строки с максимальным |M[row][col]|
        int pivot = col;
        for (int row = col + 1; row < m; row++) {
            if (std::fabs(M[row][col]) > std::fabs(M[pivot][col])) pivot = row;
        }
        if (std::fabs(M[pivot][col]) < 1e-12) {
            // вырожденная — определитель равен 0,
            // что означает: алгебраическое дополнение = 0 = граф несвязный
            return 0;
        }
        if (pivot != col) {
            std::swap(M[pivot], M[col]);
            det = -det;
        }

        det *= M[col][col];
        // 2) обнуляем под текущим столбцом
        for (int row = col + 1; row < m; row++) {
            double factor = M[row][col] / M[col][col];
            for (int k = col; k < m; k++) {
                M[row][k] -= factor * M[col][k];
            }
        }
    }

    // Округляем — число остовных деревьев заведомо целое.
    return (long long)std::llround(det);
}

void Graph::printKirchhoffResult() const {
    if (vertexCount == 0) {
        std::cout << "Сначала необходимо сгенерировать граф.\n";
        return;
    }
    this->printUndirected();

    long long count = countSpanningTreesKirchhoff();

    std::cout << "\nЧисло остовных деревьев (теорема Кирхгофа): " << count << "\n";

    if (count == 0) {
        std::cout << "(граф несвязный — остовного дерева не существует)\n";
    } else if (vertexCount == 2) {
        std::cout << "(K2: единственное остовное дерево — это само ребро)\n";
    } else if (vertexCount == 1) {
        std::cout << "(одна вершина — тривиальный случай)\n";
    }
}